import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const directory = new URL('../web/design-system/', import.meta.url);
export async function designTokens(checkOnly = false) {
  const tokens = JSON.parse(await readFile(new URL('tokens.json', directory), 'utf8'));
  const declarations = (values: Record<string, string>, indent = '  ') => Object.entries(values)
    .map(([name, value]) => `${indent}--motion-${name}: ${value};`).join('\n');
  const css = `/* Generated by npm run design:tokens. Edit tokens.json, not this file. */
:where([data-motion-ui]) {
${declarations(tokens.shared)}
}
:where([data-motion-ui]) {
  color-scheme: light;
${declarations(tokens.themes.light)}
}
:where([data-motion-ui][data-theme="dark"], [data-motion-ui][data-motion-studio]:not([data-theme="paper"])) {
  color-scheme: dark;
${declarations(tokens.themes.dark)}
}
@media (prefers-color-scheme: dark) {
  :where([data-motion-ui]:not([data-theme]):not([data-motion-studio])) {
    color-scheme: dark;
${declarations(tokens.themes.dark, '    ')}
  }
}
`;
  if (checkOnly) {
    if (await readFile(new URL('tokens.css', directory), 'utf8') !== css) throw new Error('Design tokens are stale. Run npm run design:tokens.');
  } else await writeFile(new URL('tokens.css', directory), css);
  return tokens;
}
if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  await designTokens(process.argv.includes('--check'));
  console.log(process.argv.includes('--check') ? 'Design tokens are in sync.' : 'Generated web/design-system/tokens.css');
}
