export function localizePluginInputLabel(locale: Locale, field: InputFieldSpec): string {
  const label = field.label ?? field.name;
  if (locale === 'zh-CN') return ZH_INPUT_LABELS[label] ?? label;
  if (locale === 'tr') return TR_INPUT_LABELS[label] ?? label;
  return label;
}

export function localizePluginPlaceholder(
  locale: Locale,
  value: string | undefined,
  fallback: string = '',
): string {
  const placeholder = value ?? fallback;
  if (locale === 'zh-CN') {
    return ZH_PLACEHOLDERS[placeholder] ?? ZH_DISPLAY_VALUES[placeholder] ?? placeholder;
  }
  if (locale === 'tr') {
    return TR_PLACEHOLDERS[placeholder] ?? TR_DISPLAY_VALUES[placeholder] ?? placeholder;
  }
  return placeholder;
}

export function localizePluginDisplayValue(locale: Locale, value: unknown): string {
  if (value === undefined || value === null) return '';
  const text = String(value);
  if (locale === 'zh-CN') return ZH_DISPLAY_VALUES[text] ?? text;
  if (locale === 'tr') return TR_DISPLAY_VALUES[text] ?? text;
  return text;
}
