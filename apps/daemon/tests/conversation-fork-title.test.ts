/*
 * 从一条回复「新开会话」出来的新会话叫什么。
 *
 * 2026-09-03 产品裁决:不再叫「{原标题} 分叉」,改成在**源标题**后面接一个自增编号:
 *
 *   「商品列表页」          → 「商品列表页 (1)」
 *   再来一次(已有 (1))     → 「商品列表页 (2)」
 *   「商品列表页 (1)」再来   → 「商品列表页 (2)」   ← 不是「商品列表页 (1) (1)」
 *
 * 同日补裁:**「分叉」这个词不剥**。老会话叫「商品列表页 分叉」,它的新会话就是
 * 「商品列表页 分叉 (1)」—— 老名字整个当基名,不做数据迁移,线上两种名字长期并存。
 * 要剥的只有**我们自己加的那个编号后缀**。
 *
 * 「我们自己加的编号」和「用户名字里碰巧有的括号数字」没法百分百区分。判据取的是
 * **我们自己发得出来的形状**:一个半角空格 + 半角括号 + 1~3 位、无前导零、≥1 的整数。
 * 于是「方案 (2024)」(四位数,年份)不会被误剥 —— 见下面那条反向对照。
 */
import { describe, expect, it } from 'vitest';

import { nextForkedConversationTitle } from '../src/conversation-fork-title.js';

describe('新开会话的标题编号', () => {
  it('源标题没编号时从 (1) 起步', () => {
    expect(nextForkedConversationTitle('商品列表页', ['商品列表页'])).toBe('商品列表页 (1)');
  });

  it('已经有 (1) 就接 (2)', () => {
    expect(
      nextForkedConversationTitle('商品列表页', ['商品列表页', '商品列表页 (1)']),
    ).toBe('商品列表页 (2)');
  });

  it('从「商品列表页 (1)」再开一个是 (2),不是「(1) (1)」', () => {
    expect(
      nextForkedConversationTitle('商品列表页 (1)', ['商品列表页', '商品列表页 (1)']),
    ).toBe('商品列表页 (2)');
  });

  it('源会话被删掉、只剩带编号的那个,照样接着往下数', () => {
    // 「(1) (1)」是最容易踩的坑:剥编号不能依赖「基名还在不在」这种上下文证据,
    // 因为人随时会把最早那条删掉。
    expect(nextForkedConversationTitle('商品列表页 (1)', ['商品列表页 (1)'])).toBe(
      '商品列表页 (2)',
    );
  });

  it('中间有空档时接着最大值走,不回填空档', () => {
    // 有 (1) 和 (3) 没有 (2):回填会让刚被删掉的那个名字原地复活,
    // 看起来像「删除没生效」。取 max+1。
    expect(
      nextForkedConversationTitle('商品列表页', ['商品列表页', '商品列表页 (1)', '商品列表页 (3)']),
    ).toBe('商品列表页 (4)');
  });

  it('「分叉」这个词是老标题的一部分,不剥', () => {
    expect(
      nextForkedConversationTitle('商品列表页 分叉', ['商品列表页', '商品列表页 分叉']),
    ).toBe('商品列表页 分叉 (1)');
  });

  it('老的「分叉」会话再开一个,编号只在它自己这一族里数', () => {
    expect(
      nextForkedConversationTitle('商品列表页 分叉', [
        '商品列表页',
        '商品列表页 (7)',
        '商品列表页 分叉',
        '商品列表页 分叉 (1)',
      ]),
    ).toBe('商品列表页 分叉 (2)');
  });

  it('反向对照:用户自己起的「方案 (2024)」不当编号剥', () => {
    expect(nextForkedConversationTitle('方案 (2024)', ['方案 (2024)'])).toBe('方案 (2024) (1)');
  });

  it('反向对照:别人家族的编号不参与计数', () => {
    expect(
      nextForkedConversationTitle('商品列表页', ['商品列表页', '结算页 (9)', '商品列表页详情 (5)']),
    ).toBe('商品列表页 (1)');
  });

  it('反向对照:没有标题的会话不参与计数,也不产出标题', () => {
    expect(nextForkedConversationTitle(null, ['商品列表页'])).toBeNull();
    expect(nextForkedConversationTitle('   ', ['商品列表页'])).toBeNull();
    expect(nextForkedConversationTitle('商品列表页', ['商品列表页', null, undefined, '  '])).toBe(
      '商品列表页 (1)',
    );
  });

  it('反向对照:形状对不上的括号数字既不剥也不计数', () => {
    // 前导零、0、全角括号、两个空格 —— 都不是我们发得出来的形状。
    expect(
      nextForkedConversationTitle('商品列表页', [
        '商品列表页',
        '商品列表页 (01)',
        '商品列表页 (0)',
        '商品列表页 （2）', // 全角括号
        '商品列表页  (5)', // 两个空格
      ]),
    ).toBe('商品列表页 (1)');
    expect(nextForkedConversationTitle('商品列表页 (01)', ['商品列表页 (01)'])).toBe(
      '商品列表页 (01) (1)',
    );
    // 两个空格:正则会咬住第二个空格,基名末尾剩一个空格 —— 剥了就等于把用户手起的
    // 标题悄悄削掉一截,所以这一形状整个当基名。
    expect(nextForkedConversationTitle('商品列表页  (5)', ['商品列表页  (5)'])).toBe(
      '商品列表页  (5) (1)',
    );
    // 编号从 1 起,`(0)` 我们发不出来 —— 当基名的一部分带走,不剥。
    expect(nextForkedConversationTitle('商品列表页 (0)', ['商品列表页 (0)'])).toBe(
      '商品列表页 (0) (1)',
    );
  });

  it('标题两头的空白先修掉再算', () => {
    expect(nextForkedConversationTitle('  商品列表页  ', ['商品列表页'])).toBe('商品列表页 (1)');
  });
});
